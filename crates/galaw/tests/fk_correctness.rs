// =============================================================================
// 2. GALAW VS MUJOCO FIXTURES (MJCF GROUND TRUTH)
// =============================================================================
//
// Fixtures were generated by `scripts/generate_mujoco_fk_fixtures.py` using
// the MuJoCo Python bindings as the reference implementation.  The JSON files
// are committed under `tests/fixtures/mujoco_fk/` so these tests run offline
// with no Python or MuJoCo dependency.
//
// To regenerate (required when MJCF files or the parser change):
//   uv run scripts/generate_mujoco_fk_fixtures.py

// Cross-library FK: different floating-point operation ordering between
// MuJoCo (C) and galaw (Rust/nalgebra).  1e-5 is well within double-
// precision FK error for chains up to ~30 DOF.
const MUJOCO_TOLERANCE: f64 = 1e-5;

#[derive(Deserialize)]
struct LinkPose {
    pos: [f64; 3],
    /// MuJoCo convention: w-first [w, x, y, z]
    quat_wxyz: [f64; 4],
}

#[derive(Deserialize)]
struct MujocoConfig {
    name: String,
    joint_values: HashMap<String, f64>,
    link_poses: HashMap<String, LinkPose>,
}

#[derive(Deserialize)]
struct MujocoFixture {
    #[allow(dead_code)]
    robot: String,
    configs: Vec<MujocoConfig>,
}

fn load_fixture(stem: &str) -> MujocoFixture {
    let path = format!("tests/fixtures/mujoco_fk/{stem}.json");
    let content = std::fs::read_to_string(&path).unwrap_or_else(|_| {
        panic!(
            "fixture not found: {path}\n  \
             regenerate with: uv run scripts/generate_mujoco_fk_fixtures.py"
        )
    });
    serde_json::from_str(&content).unwrap_or_else(|e| {
        panic!("fixture JSON is malformed ({path}): {e}")
    })
}

fn to_isometry(pose: &LinkPose) -> Isometry3<f64> {
    let [x, y, z] = pose.pos;
    let [w, qx, qy, qz] = pose.quat_wxyz;
    Isometry3::from_parts(
        Translation3::new(x, y, z),
        UnitQuaternion::new_normalize(Quaternion::new(w, qx, qy, qz)),
    )
}

fn assert_pose_close(
    actual: &Isometry3<f64>,
    expected: &Isometry3<f64>,
    config_name: &str,
    link_name: &str,
) {
    let dt = actual.translation.vector - expected.translation.vector;
    assert!(
        dt.norm() < MUJOCO_TOLERANCE,
        "config={config_name:?} link={link_name:?}: \
         position error {:.2e} >= tolerance {MUJOCO_TOLERANCE:.0e}\n  \
         galaw:   {:?}\n  mujoco:  {:?}",
        dt.norm(),
        actual.translation.vector,
        expected.translation.vector,
    );

    let dot = (actual.rotation.quaternion().dot(expected.rotation.quaternion())).abs();
    assert!(
        (dot - 1.0).abs() < MUJOCO_TOLERANCE,
        "config={config_name:?} link={link_name:?}: \
         rotation dot-product error {:.2e} >= tolerance {MUJOCO_TOLERANCE:.0e}\n  \
         galaw:   {:?}\n  mujoco:  {:?}",
        (dot - 1.0).abs(),
        actual.rotation,
        expected.rotation,
    );
}

fn check_mujoco_fk(mjcf_path: &str, fixture: &MujocoFixture) -> TestResult {
    let model = load_mjcf::<f64>(mjcf_path)
        .unwrap_or_else(|e| panic!("failed to load {mjcf_path}: {e}"));

    for config in &fixture.configs {
        // Build cmds in galaw's cmd_idx order from the fixture joint values.
        // Joints that only exist in MuJoCo (ball, etc.) are simply absent from
        // the fixture and will stay at the default 0.0 in cmds.
        let mut cmds = vec![0.0_f64; model.num_actuated_joints];
        for (joint_name, &value) in &config.joint_values {
            if let Some(cmd_idx) = model.get_joint_idx(joint_name) {
                cmds[cmd_idx] = value;
            }
        }

        let mut data = model.create_galaw_data();
        model.compute_fk(&cmds, &mut data).unwrap();

        // Compare every link that appears in both the fixture and galaw's model.
        // Skips MuJoCo-only bodies (none expected for these models) and
        // galaw virtual links (created for multi-joint or offset-anchor bodies).
        for (link_name, expected_pose) in &config.link_poses {
            let Some(link_idx) = model.get_link_idx(link_name) else {
                continue;
            };
            assert_pose_close(
                &data.link_poses[link_idx],
                &to_isometry(expected_pose),
                &config.name,
                link_name,
            );
        }
    }
    Ok(())
}

macro_rules! mujoco_fk_tests {
    ($($name:ident => ($fixture:expr, $path:expr)),* $(,)?) => {
        $(
            #[test]
            fn $name() -> TestResult {
                let fixture = load_fixture($fixture);
                check_mujoco_fk($path, &fixture)
            }
        )*
    };
}

