// =============================================================================
// 5. CODEGEN VS RUNTIME
// =============================================================================

/// Compares a codegen'd `compute_fk` against the dynamic `GalawModel::compute_fk`
/// over many random poses, not just one hand-picked pose. Generic over the array
/// sizes baked into each robot's generated signature (`[f64; N] -> [Isometry3<f64>; M]`),
/// since those differ per robot and can't be unified any other way without codegen
/// itself producing a shared trait. The dynamic path is the ground truth here
/// (already checked against `k` above), so this only needs to confirm the
/// generated code agrees with it.
fn check_generated_matches_runtime<const NUM_JOINTS: usize, const NUM_LINKS: usize>(
    model_path: &str,
    generated_compute_fk: impl Fn(
        &[f64; NUM_JOINTS],
        &mut GeneratedGalawData<f64, NUM_JOINTS, NUM_LINKS>,
    ),
) -> TestResult {
    let galaw_model = if model_path.ends_with(".xml") {
        load_mjcf::<f64>(model_path).unwrap()
    } else {
        load_urdf::<f64>(model_path).unwrap()
    };
    let mut data = galaw_model.create_galaw_data();
    let mut gen_data = GeneratedGalawData::new();

    let mut rng = ChaCha8Rng::seed_from_u64(RNG_SEED);
    for _ in 0..NUM_POSES {
        let joint_cmds: Vec<f64> = galaw_model
            .joints
            .iter()
            .filter(|j| j.cmd_idx.is_some())
            .map(|j| match (j.limit_lower, j.limit_upper) {
                (Some(lower), Some(upper)) => rng.random_range(lower..upper),
                _ => rng.random_range(0.0..0.0),
            })
            .collect();

        galaw_model.compute_fk(&joint_cmds, &mut data)?;

        let joint_cmds_arr: [f64; NUM_JOINTS] = joint_cmds.clone().try_into().unwrap();
        generated_compute_fk(&joint_cmds_arr, &mut gen_data);

        for i in 0..galaw_model.num_links {
            assert_galaw_transform_close(
                &data.link_poses[i],
                &gen_data.link_poses[i],
                &TEST_TOLERANCE,
            );
        }
    }

    Ok(())
}

macro_rules! codegen_correctness_test {
    ($module:ident, $path:expr, $compute_fk:path) => {
        mod $module {
            use super::*;

            #[test]
            fn matches_runtime() -> TestResult {
                check_generated_matches_runtime($path, $compute_fk)
            }
        }
    };
}
galaw::for_each_generated_robot!(codegen_correctness_test);
